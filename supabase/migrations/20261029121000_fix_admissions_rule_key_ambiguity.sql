-- PH-3 reliability/observability:
-- The first restored Admissions cron run reached the existing automation RPC
-- and exposed a PL/pgSQL name-resolution ambiguity: RETURNS TABLE defines an
-- output parameter named rule_key, while the event insert uses rule_key in the
-- ON CONFLICT inference target. Keep the public contract and automation logic
-- unchanged; resolve ambiguous SQL identifiers as table columns in this
-- function only.

create or replace function public.run_admissions_auto_tasks(
  p_organization_id uuid,
  p_dry_run boolean default true
)
returns table(
  lead_id uuid,
  lead_code text,
  lead_name text,
  rule_key text,
  task_title text,
  due_at timestamptz,
  result text
)
language plpgsql
security definer
set search_path to 'public'
as $function$
#variable_conflict use_column
declare
  r record;
begin

  if p_organization_id is null then
    raise exception 'Organization is required';
  end if;

  if not exists (
    select 1
    from public.organizations o
    where o.id = p_organization_id
  ) then
    raise exception
      'Organization % does not exist',
      p_organization_id;
  end if;

  for r in

    select
      c.*
    from public.v_admissions_auto_task_candidates c

    where c.organization_id = p_organization_id

      and c.rule_key is not null
      and c.event_key is not null

      and not exists (
        select 1
        from public.admissions_auto_task_events e
        where e.organization_id = p_organization_id
          and e.rule_key = c.rule_key
          and e.event_key = c.event_key
      )

    order by
      c.priority_score desc nulls last,
      c.proposed_due_at asc

  loop

    if p_dry_run then

      return query
      select
        r.lead_id,
        r.lead_code,
        r.lead_name,
        r.rule_key,
        r.task_title,
        r.proposed_due_at,
        'preview'::text;

    else

      begin

        perform public.create_followup_task(
          r.lead_id,
          r.task_title,
          r.proposed_due_at,
          concat_ws(
            ' | ',
            'Auto-generated by Admissions Rules Engine',
            r.next_best_action,
            r.priority_reason
          )
        );

        insert into public.admissions_auto_task_events (
          organization_id,
          lead_id,
          rule_key,
          event_key,
          task_title,
          task_due_at,
          priority_score,
          next_best_action,
          priority_reason
        )
        values (
          p_organization_id,
          r.lead_id,
          r.rule_key,
          r.event_key,
          r.task_title,
          r.proposed_due_at,
          r.priority_score,
          r.next_best_action,
          r.priority_reason
        )
        on conflict (organization_id, rule_key, event_key)
        do nothing;

        return query
        select
          r.lead_id,
          r.lead_code,
          r.lead_name,
          r.rule_key,
          r.task_title,
          r.proposed_due_at,
          'created'::text;

      exception
        when others then

          return query
          select
            r.lead_id,
            r.lead_code,
            r.lead_name,
            r.rule_key,
            r.task_title,
            r.proposed_due_at,
            ('failed: ' || sqlerrm)::text;

      end;

    end if;

  end loop;

  return;

end;
$function$;

comment on function public.run_admissions_auto_tasks(uuid, boolean) is
  'Admissions auto-task runner. PH-3 compatibility fix resolves PL/pgSQL rule_key ambiguity as table-column precedence while preserving the existing public result contract and idempotency behavior.';
