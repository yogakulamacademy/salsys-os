/**
 * Offline reference model for a durable import ledger. Pure transitions only.
 * Does not authorize callers, lock database rows, create documents or execute jobs.
 * Future database implementation must serialize each transition in a transaction.
 */
export const KNOWLEDGE_IMPORT_PROCESSING_WIRED = false as const;
export const MAX_ATTEMPTS = 5;
export const LEASE_MS = 120_000;
export const MAX_CLAIM = 50;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const uuid = (value: unknown): value is string => typeof value === 'string' && UUID.test(value);
const time = (n: number) => Number.isSafeInteger(n) && n >= 0 && n <= Number.MAX_SAFE_INTEGER - 600_000;
type Scope = Readonly<{ organizationId: string; jobId: string }>;
type Status = 'pending' | 'leased' | 'created' | 'invalid' | 'duplicate' | 'failed' | 'cancelled';
type Entry = Readonly<{ index: number; status: Status; attempts: number; availableAt: number; leaseToken: string | null; leaseUntil: number | null; documentId: string | null }>;
type Job = Readonly<Scope & { sourceDigest: string; status: 'queued' | 'processing' | 'completed' | 'cancelled' | 'expired'; expiresAt: number; entries: readonly Entry[] }>;
type Disposition = Readonly<{ index: number; status: 'pending' | 'invalid' | 'duplicate' }>;
type Claim = Readonly<Scope & { index: number; token: string; attempt: number }>;
type Outcome = { kind: 'created'; documentId: string; organizationId: string; documentStatus: 'draft' } | { kind: 'retry' } | { kind: 'failed' };
const terminal = (s: Status) => s !== 'pending' && s !== 'leased';
const clearLease = (e: Entry, status: Status, availableAt = e.availableAt): Entry => ({...e,status,availableAt,leaseToken:null,leaseUntil:null});
const bound = (job: Job, scope: Scope) => job.organizationId === scope.organizationId && job.jobId === scope.jobId;
const runnable = (job: Job, scope: Scope, now: number) => bound(job,scope) && time(now) && now < job.expiresAt && (job.status === 'queued' || job.status === 'processing');
function rollup(job: Job, entries: readonly Entry[]): Job {
  return {...job,entries,status: entries.every(e=>terminal(e.status)) ? 'completed' : 'processing'};
}
/** Input dispositions must be generated by verified server preflight; no raw document data is stored. */
export function createImportLedgerPreview(scope: Scope, sourceDigest: string, total: number, dispositions: readonly Disposition[], now: number, expiresAt: number): Job | null {
  if (!uuid(scope.organizationId) || !uuid(scope.jobId) || !/^[a-f0-9]{64}$/.test(sourceDigest) || !time(now) || !time(expiresAt) || expiresAt <= now ||
      !Number.isSafeInteger(total) || total < 1 || total > 10_000 || dispositions.length !== total) return null;
  const seen = new Set<number>();
  const entries: Entry[] = [];
  for (const d of dispositions) {
    if (!Number.isSafeInteger(d.index) || d.index < 0 || d.index >= total || seen.has(d.index) || !['pending','invalid','duplicate'].includes(d.status)) return null;
    seen.add(d.index);
    entries.push({index:d.index,status:d.status,attempts:0,availableAt:now,leaseToken:null,leaseUntil:null,documentId:null});
  }
  entries.sort((a,b)=>a.index-b.index);
  return {...scope,sourceDigest,expiresAt,entries,status:entries.every(e=>terminal(e.status))?'completed':'queued'};
}
/** Reference claim; real workers must lock the job and compare/update entry rows atomically. */
export function claimImportPreview(job: Job, scope: Scope, now: number, token: string, limit = MAX_CLAIM): {job: Job; claims: Claim[]} | null {
  if (!runnable(job,scope,now) || !uuid(token) || !Number.isSafeInteger(limit) || limit < 1 || limit > MAX_CLAIM) return null;
  const claims: Claim[] = [];
  const entries = job.entries.map(e=>{
    const expired = e.status === 'leased' && e.leaseUntil !== null && e.leaseUntil <= now;
    if (expired && e.attempts >= MAX_ATTEMPTS) return clearLease(e,'failed');
    if (claims.length >= limit || !(expired || (e.status === 'pending' && e.availableAt <= now))) return e;
    if (e.attempts >= MAX_ATTEMPTS) return clearLease(e,'failed');
    const attempt = e.attempts + 1;
    claims.push({...scope,index:e.index,token,attempt});
    return {...e,status:'leased' as const,attempts:attempt,leaseToken:token,leaseUntil:Math.min(now+LEASE_MS,job.expiresAt)};
  });
  return {job:rollup(job,entries),claims};
}
/** Created outcome is a simulated result only. Actual draft creation + ledger update must be one DB transaction. */
export function settleImportPreview(job: Job, claim: Claim, now: number, outcome: Outcome): Job | null {
  if (!runnable(job,claim,now)) return null;
  const entry = job.entries.find(e=>e.index===claim.index);
  if (!entry || entry.status !== 'leased' || entry.leaseToken !== claim.token || entry.attempts !== claim.attempt || entry.leaseUntil === null || now >= entry.leaseUntil) return null;
  let next: Entry;
  if (outcome.kind === 'created') {
    if (outcome.organizationId !== job.organizationId || outcome.documentStatus !== 'draft' || !uuid(outcome.documentId) || job.entries.some(e=>e.documentId===outcome.documentId)) return null;
    next = {...clearLease(entry,'created'),documentId:outcome.documentId};
  } else if (outcome.kind === 'retry' && entry.attempts < MAX_ATTEMPTS) {
    next = clearLease(entry,'pending',now+30_000*2**(entry.attempts-1));
  } else if (outcome.kind === 'failed' || outcome.kind === 'retry') {
    next = clearLease(entry,'failed');
  } else return null;
  return rollup(job,job.entries.map(e=>e.index===entry.index?next:e));
}
/** Cancellation/expiry preserve completed drafts. Real DB must serialize with commit. */
export function stopImportPreview(job: Job, scope: Scope, now: number, reason: 'cancelled' | 'expired'): Job | null {
  if (!bound(job,scope) || !time(now) || (job.status!=='queued' && job.status!=='processing') ||
      (reason==='expired' && now<job.expiresAt) || (reason==='cancelled' && now>=job.expiresAt) || !['expired','cancelled'].includes(reason)) return null;
  return {...job,status:reason,entries:job.entries.map(e=>terminal(e.status)?e:clearLease(e,'cancelled'))};
}
export function importProgressPreview(job: Job) {
  const counts: Record<Status,number> = {pending:0,leased:0,created:0,invalid:0,duplicate:0,failed:0,cancelled:0};
  for(const entry of job.entries) counts[entry.status]++;
  const total=job.entries.length, remaining=counts.pending+counts.leased, processed=total-remaining;
  return {total,processed,remaining,counts,percent:total?Math.floor(processed*100/total):0};
}
